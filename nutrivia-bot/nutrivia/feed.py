"""Лента сообщества: рецепты и привычки участников. Результаты — привычками (серия, белок), не килограммами:
вес и «минус N кг» в постах не публикуем (риск РПП из обзора 06.10). Модерация: жалобы и скрытие оператором."""
import re

KINDS = ("recipe", "habit")
HIDE_AFTER_REPORTS = 3  # столько жалоб от разных людей — пост скрывается до решения оператора

_WEIGHT = re.compile(r"\d+[.,]?\d*\s*(кг|kg|килограмм)|(минус|скинул|скинула|похудел|похудела|сбросил|сбросила)\s*\d",
                     re.IGNORECASE)


def check_text(text: str) -> str | None:
    """None — можно публиковать; иначе — почему нельзя."""
    t = text.strip()
    if len(t) < 3:
        return "Напишите хотя бы пару слов."
    if _WEIGHT.search(t):
        return "В ленте делимся привычками и рецептами, без килограммов."
    return None
